    """Traduce una clave al idioma dado (respaldo: espanol, luego la clave)."""
    catalog = MESSAGES.get(language) or MESSAGES["es"]
    template = catalog.get(key) or MESSAGES["es"].get(key) or key
    try:
        return template.format(**kwargs) if kwargs else template
    except (KeyError, IndexError):
        return template
